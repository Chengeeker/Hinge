"""Port the vendored liquid-glass shaders without rewriting their optics.

Run with --check to verify the generated GLES shaders.
"""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).resolve().parent / "reference/glass-upstream"
TARGET = ROOT / "android-compose/app/src/main/assets/glass"


def read(name):
    return (SOURCE / name).read_text(encoding="utf-8-sig")


def gles(text):
    text = re.sub(r"^#version .*\n", "", text, flags=re.M)
    text = text.replace("#include <flutter/runtime_effect.glsl>", "")
    text = text.replace('#include "gles_compat.glsl"', "")
    text = re.sub(r"layout\(location = \d+\) uniform", "uniform", text)
    text = text.replace("layout(location = 0) out vec4 fragColor;", "#define fragColor gl_FragColor")
    return text.replace("texture(", "texture2D(")


def shaders():
    geometry = read("liquid_glass_geometry_blended.frag")
    # This bar has one shape per optical layer. Keep the original single-shape
    # SDF, avoiding 112 unused scalar uniforms on GLES 2 devices.
    sdf = read("sdf.glsl")
    rrect = sdf[sdf.index("float sdfRRect("):sdf.index("float sdfRRectAsym(")]
    geometry = geometry.replace("#define MAX_SHAPES 16", "#define MAX_SHAPES 1")
    geometry = geometry.replace('#include "sdf.glsl"', rrect + """
float sceneSDF(vec2 p, int n, float blend) {
    return sdfRRect(p - vec2(uShapeData[1], uShapeData[2]),
        vec2(uShapeData[3], uShapeData[4]) * 0.5, uShapeData[5]);
}
""")
    geometry = geometry.replace('#include "displacement_encoding.glsl"', read("displacement_encoding.glsl"))
    geometry = geometry.replace("FlutterFragCoord().xy", "(gl_FragCoord.xy - uTransform.xy) / uTransform.zw + uTransform.xy")
    geometry = geometry.replace("uniform vec2 uSize;", "uniform vec2 uSize;\nuniform vec4 uTransform;")

    render = read("liquid_glass_render.frag")
    render = render.replace('#include "displacement_encoding.glsl"', read("displacement_encoding.glsl"))
    render = render.replace('#include "render.glsl"', read("render.glsl"))
    render = render.replace("FlutterFragCoord().xy", "gl_FragCoord.xy")
    render = render.replace("uniform vec2 uSize;", """uniform vec2 uSize;
uniform vec2 uBackdropSize;
uniform vec2 uCropOrigin;
""")
    render = render.replace("texture(uGeometryTexture, geometryUV)", "texture(uGeometryTexture, fragCoord / uSize)")
    # Flutter pinch is normalized against the enclosing screen pass, NOT the
    # cropped nav texture. Convert through that space before sampling our crop.
    assert render.count("screenUV += pinchShift;") == 1
    assert render.count("screenUV = clamp(screenUV, vec2(0.001), vec2(0.999));") == 1
    render = render.replace("screenUV += pinchShift;", """vec2 backdropUV = (fragCoord + uCropOrigin) / uBackdropSize;
        backdropUV = clamp(backdropUV + pinchShift, vec2(0.001), vec2(0.999));
        screenUV = (backdropUV * uBackdropSize - uCropOrigin) / uSize;""")
    render = render.replace("screenUV = clamp(screenUV, vec2(0.001), vec2(0.999));", "")
    render = render.replace("max(70.0 * dpr, uSize.y * 1.5)", "max(70.0 * dpr, uBackdropSize.y * 1.5)")
    return {"flutter_geometry.glsl": gles(geometry), "flutter_render.glsl": gles(render)}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in shaders().items():
        content = "// Generated by tools/sync_glass_shaders.py; edit the adapter, not this file.\n" + content
        target = TARGET / name
        if args.check:
            assert target.read_text(encoding="utf-8") == content, f"Stale Flutter shader port: {target}"
        else:
            target.write_text(content, encoding="utf-8", newline="\n")
        print(("Verified " if args.check else "Generated ") + name)
